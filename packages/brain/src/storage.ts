/**
 * Recording storage — the ONLY module that knows where event files live.
 *
 * Everything else in the system asks this module and cannot tell whether the
 * bytes are on local disk or in object storage. That is deliberate: swapping
 * to S3/R2 when you outgrow one machine should be a change in this file and
 * nowhere else.
 *
 * Format is newline-delimited JSON, one event per line, appended as batches
 * arrive. Appending never reads what's already there, so a long session costs
 * the same to write as a short one, and playback streams the file rather than
 * loading it into memory on the server.
 */

import { createReadStream } from "node:fs";
import { appendFile, mkdir, rm, stat } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";

const DATA_DIR = process.env.DATA_DIR ?? "./data";
const EVENTS_DIR = path.resolve(DATA_DIR, "events");

/** Session ids are generated by us, but this is the boundary — check anyway. */
const SAFE_ID = /^[A-Za-z0-9_-]{8,64}$/;

function fileFor(sessionId: string): string {
  if (!SAFE_ID.test(sessionId)) {
    throw new Error("unsafe session id");
  }
  return path.join(EVENTS_DIR, `${sessionId}.ndjson`);
}

export async function appendEvents(
  sessionId: string,
  events: unknown[],
): Promise<number> {
  if (events.length === 0) return 0;
  await mkdir(EVENTS_DIR, { recursive: true });
  const lines = events.map((e) => JSON.stringify(e)).join("\n") + "\n";
  await appendFile(fileFor(sessionId), lines, "utf8");
  return Buffer.byteLength(lines, "utf8");
}

export function readEventStream(sessionId: string): Readable {
  return createReadStream(fileFor(sessionId), { encoding: "utf8" });
}

export async function eventsExist(sessionId: string): Promise<boolean> {
  try {
    await stat(fileFor(sessionId));
    return true;
  } catch {
    return false;
  }
}

export async function deleteEvents(sessionId: string): Promise<void> {
  await rm(fileFor(sessionId), { force: true });
}
